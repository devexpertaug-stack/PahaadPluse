"""Build the checked-in sample dataset JSON + datasheet (Req 2.8).

Run with: ``uv run python scripts/build_dataset.py``. Writes
``data/sample_reviews/mussoorie_reviews.json`` (enriched, schema-valid records)
and regenerates the counts section of ``data/datasheet.md`` so the datasheet
record counts always match the actual dataset.
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

from app.services.market_radar.parsing import ReviewPrinter

from app.seed.sample_reviews import (  # isort: skip
    CLUSTER_NAME,
    COLLECTION_DATE_RANGE,
    PROPERTIES,
    build_review_records,
)

_REPO_ROOT = Path(__file__).resolve().parents[2]
_DATA_DIR = _REPO_ROOT / "data" / "sample_reviews"
_DATASHEET = _REPO_ROOT / "data" / "datasheet.md"


def _write_json(records: list) -> None:
    printer = ReviewPrinter()
    payload = [printer.to_dict(r) for r in records]
    _DATA_DIR.mkdir(parents=True, exist_ok=True)
    out = _DATA_DIR / "mussoorie_reviews.json"
    out.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {out} ({len(payload)} records)")


def _counts(records: list) -> tuple[Counter, Counter, Counter, Counter]:
    per_platform = Counter(r.platform for r in records)
    per_property = Counter(r.property_name for r in records)
    per_language = Counter(r.detected_language for r in records)
    per_prop_platform: Counter = Counter((r.property_name, r.platform) for r in records)
    return per_platform, per_property, per_language, per_prop_platform


def _render_counts_section(records: list) -> str:
    per_platform, per_property, per_language, per_pp = _counts(records)
    prop_names = [p.name for p in PROPERTIES]
    platforms = sorted(per_platform)

    lines: list[str] = []
    lines.append("<!-- COUNTS:AUTO-GENERATED by scripts/build_dataset.py — do not edit by hand -->")
    lines.append("")
    lines.append(f"- **Total records:** {len(records)}")
    lines.append(f"- **Cluster:** {CLUSTER_NAME}")
    lines.append(f"- **Properties:** {len(prop_names)}")
    lines.append(
        f"- **Collection date range:** {COLLECTION_DATE_RANGE[0]} to {COLLECTION_DATE_RANGE[1]}"
    )
    lines.append("")
    lines.append("### Records per platform")
    lines.append("")
    lines.append("| Platform | Records |")
    lines.append("| --- | --- |")
    for platform in platforms:
        lines.append(f"| {platform} | {per_platform[platform]} |")
    lines.append("")
    lines.append("### Records per property")
    lines.append("")
    lines.append("| Property | Records |")
    lines.append("| --- | --- |")
    for name in prop_names:
        lines.append(f"| {name} | {per_property[name]} |")
    lines.append("")
    lines.append("### Records per property × platform")
    lines.append("")
    header = "| Property | " + " | ".join(platforms) + " | Total |"
    sep = "| --- | " + " | ".join(["---"] * len(platforms)) + " | --- |"
    lines.append(header)
    lines.append(sep)
    for name in prop_names:
        cells = [str(per_pp.get((name, p), 0)) for p in platforms]
        total = sum(int(c) for c in cells)
        lines.append(f"| {name} | " + " | ".join(cells) + f" | {total} |")
    lines.append("")
    lines.append("### Records per detected language")
    lines.append("")
    lines.append("| Language | Records |")
    lines.append("| --- | --- |")
    for lang in sorted(per_language):
        lines.append(f"| {lang} | {per_language[lang]} |")
    lines.append("")
    return "\n".join(lines)


_START = "<!-- COUNTS:START -->"
_END = "<!-- COUNTS:END -->"


def _update_datasheet(records: list) -> None:
    section = _render_counts_section(records)
    block = f"{_START}\n{section}\n{_END}"
    text = _DATASHEET.read_text(encoding="utf-8")
    start = text.index(_START)
    end = text.index(_END) + len(_END)
    new_text = text[:start] + block + text[end:]
    _DATASHEET.write_text(new_text, encoding="utf-8")
    print(f"updated counts in {_DATASHEET}")


def main() -> None:
    records = build_review_records(enrich_records=True)
    _write_json(records)
    _update_datasheet(records)


if __name__ == "__main__":
    main()
